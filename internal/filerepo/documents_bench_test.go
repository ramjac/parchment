func BenchmarkLoadDocumentTrackedChanges(b *testing.B) {
	ctx := context.Background()
	repo, err := New(b.TempDir(), Options{})
	if err != nil {
		b.Fatal(err)
	}
	service := document.NewService(repo, 10)
	path := filepath.Join(b.TempDir(), "document.md")
	d, err := service.Create(ctx, path, document.Draft{Body: strings.Repeat("Paragraph.\n", 1000)})
	if err != nil {
		b.Fatal(err)
	}
	_, err = service.ModifyWithTracking(ctx, path, "edit", true, func(d *document.Document) error {
		d.Body += "\ntracked addition"
		return nil
	})
	if err != nil {
		b.Fatal(err)
	}
	_ = d
	b.ResetTimer()
	for i := 0; i < b.N; i++ {
		if _, err := repo.GetDocument(ctx, path); err != nil {
			b.Fatal(err)
		}
	}
}
